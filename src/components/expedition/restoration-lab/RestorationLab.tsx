// RestorationLab — customisation reframed as restoration: original, intervention, restored specimen
import { useMemo, useRef, useState, type CSSProperties } from 'react';
import { DesignArt } from '@/lib/DesignArt';
import { useSizeBand } from '@/lib/useSizeBand';
import {
  DEFINITION_COPY,
  FABRICS,
  GARMENTS,
  THREADS,
  definition,
  relativeLuminance,
  threadByCode,
} from '@/lib/embroidery';
import { RESOLVED, fabricById, type ResolvedArtifact } from '@/lib/expedition';

export interface RestorationState {
  fabricId: string;
  garmentId: string;
  zoneId: string;
  /** Finished width on the cloth, in millimetres. */
  widthMm: number;
  /** Per-block thread overrides. Absent blocks keep the original thread. */
  threads: Record<string, string>;
}

export interface RestorationLabProps {
  artifact?: ResolvedArtifact;
  value?: RestorationState;
  defaultValue?: Partial<RestorationState>;
  onChange?: (state: RestorationState) => void;
  /** Given a handler, the lab closes with a commit action. */
  onCommit?: (state: RestorationState) => void;
  commitLabel?: string;
  className?: string;
}

type Tool = 'ground' | 'thread' | 'placement' | 'scale';

const TOOLS: { id: Tool; label: string; hint: string }[] = [
  { id: 'ground', label: 'Ground', hint: 'The cloth the piece is worked on' },
  { id: 'thread', label: 'Thread', hint: 'Re-thread a single block' },
  { id: 'placement', label: 'Placement', hint: 'Where on the carrier it sits' },
  { id: 'scale', label: 'Scale', hint: 'Finished width in millimetres' },
];

/**
 * Customisation as restoration.
 *
 * A configurator that asks for six choices up front is a form, and a form makes
 * the customer responsible for imagining the result. A restoration bench does
 * the opposite: the object is on the table the whole time, one intervention is
 * live at a time, and every change is written into a record you can read back
 * and undo. That is both a better metaphor and a better UX — it removes the
 * question "what have I actually changed?" that ordinary configurators leave
 * hanging right up until checkout.
 *
 * So the component is a large specimen and a single contextual tool, never a
 * wizard. The original stays on the bench beside the restored piece (wide), or
 * one press away (compact), because the comparison *is* the reassurance. The
 * intervention log between them is generated by diffing state against the
 * original record, so it cannot describe a change that did not happen.
 *
 * Thread choices are scored against the ground with the library's own
 * `definition()` — the same production judgement the embroidery group uses — so
 * the lab will tell a customer that their tone-on-tone choice is going to
 * disappear before they pay for it.
 *
 * Desktop puts the tool beside the bench; compact puts it in a fixed bottom
 * tray so the controls stay under the thumb and the specimen stays visible.
 */
export function RestorationLab({
  artifact = RESOLVED[0],
  value,
  defaultValue,
  onChange,
  onCommit,
  commitLabel = 'Commit restoration',
  className = '',
}: RestorationLabProps) {
  const rootRef = useRef<HTMLElement>(null);
  const band = useSizeBand(rootRef, { regular: 640, wide: 1020 });

  const original: RestorationState = useMemo(
    () => ({
      fabricId: artifact.record.fabricId,
      garmentId: artifact.record.garmentId,
      zoneId: artifact.garment.zones[0].id,
      widthMm: artifact.design.widthMm,
      threads: {},
    }),
    [artifact],
  );

  const [internal, setInternal] = useState<RestorationState>({ ...original, ...defaultValue });
  const state = value ?? internal;
  const [tool, setTool] = useState<Tool>('ground');
  const [blockId, setBlockId] = useState(artifact.design.blocks[0].id);
  const [showOriginal, setShowOriginal] = useState(false);

  const patch = (next: Partial<RestorationState>) => {
    const merged = { ...state, ...next };
    if (value === undefined) setInternal(merged);
    onChange?.(merged);
  };

  const fabric = fabricById(state.fabricId);
  const garment = GARMENTS.find((g) => g.id === state.garmentId) ?? artifact.garment;
  const zone = garment.zones.find((z) => z.id === state.zoneId) ?? garment.zones[0];
  const block = artifact.design.blocks.find((b) => b.id === blockId) ?? artifact.design.blocks[0];
  const blockThread = threadByCode(state.threads[block.id] ?? block.thread);
  const def = definition(blockThread.hex, fabric.hex);

  /** The intervention log: state diffed against the original record. */
  const log = useMemo(() => {
    const out: { key: string; from: string; to: string }[] = [];
    if (state.fabricId !== original.fabricId) {
      out.push({
        key: 'Ground',
        from: fabricById(original.fabricId).name,
        to: fabricById(state.fabricId).name,
      });
    }
    if (state.garmentId !== original.garmentId) {
      out.push({
        key: 'Carrier',
        from: artifact.garment.name,
        to: garment.name,
      });
    }
    if (state.zoneId !== original.zoneId) {
      out.push({
        key: 'Placement',
        from: artifact.garment.zones[0].label,
        to: zone.label,
      });
    }
    if (Math.round(state.widthMm) !== Math.round(original.widthMm)) {
      out.push({
        key: 'Scale',
        from: `${Math.round(original.widthMm)}mm`,
        to: `${Math.round(state.widthMm)}mm`,
      });
    }
    for (const b of artifact.design.blocks) {
      const code = state.threads[b.id];
      if (!code || code === b.thread) continue;
      out.push({
        key: b.label,
        from: threadByCode(b.thread).name,
        to: threadByCode(code).name,
      });
    }
    return out;
  }, [state, original, artifact, garment, zone]);

  const compact = band === 'compact';

  return (
    <section ref={rootRef} className={`exp exp-lab ${className}`} aria-label="Restoration bench">
      <div className="exp-lab__grid exp-section">
        <header className="exp-lab__head">
          <div>
            <span className="exp-label">Restoration bench</span>
            <h3 className="exp-title">{artifact.record.name}</h3>
          </div>
          <div className="exp-lab__headActions">
            {compact && (
              <button
                type="button"
                className="exp-action exp-action--quiet"
                aria-pressed={showOriginal}
                onClick={() => setShowOriginal((v) => !v)}
              >
                {showOriginal ? 'Show restored' : 'Show original'}
              </button>
            )}
            <button
              type="button"
              className="exp-action exp-action--quiet"
              disabled={log.length === 0}
              onClick={() => patch(original)}
            >
              Revert
            </button>
          </div>
        </header>

        <div className="exp-lab__bench">
          {!compact && (
            <figure className="exp-lab__specimen exp-lab__specimen--original">
              <Bench
                artifact={artifact}
                fabricId={original.fabricId}
                garmentId={original.garmentId}
                zoneId={original.zoneId}
                widthMm={original.widthMm}
                threads={original.threads}
                muted
              />
              <figcaption className="exp-label">Original · as recorded</figcaption>
            </figure>
          )}

          <figure className="exp-lab__specimen">
            <Bench
              artifact={artifact}
              fabricId={compact && showOriginal ? original.fabricId : state.fabricId}
              garmentId={compact && showOriginal ? original.garmentId : state.garmentId}
              zoneId={compact && showOriginal ? original.zoneId : state.zoneId}
              widthMm={compact && showOriginal ? original.widthMm : state.widthMm}
              threads={compact && showOriginal ? original.threads : state.threads}
              highlightZone={tool === 'placement'}
            />
            <figcaption className="exp-label exp-label--ink">
              {compact && showOriginal
                ? 'Original · as recorded'
                : log.length
                  ? `Restored · ${log.length} intervention${log.length > 1 ? 's' : ''}`
                  : 'Restored · no intervention yet'}
            </figcaption>
          </figure>
        </div>

        <div className="exp-lab__log" aria-live="polite">
          <span className="exp-label">Intervention record</span>
          {log.length === 0 ? (
            <p className="exp-caption">Nothing changed. The specimen is as it was recorded.</p>
          ) : (
            <ul className="exp-lab__logList">
              {log.map((l) => (
                <li key={l.key + l.to}>
                  <span className="exp-meta">{l.key}</span>
                  <span className="exp-lab__logFrom">{l.from}</span>
                  <svg width="18" height="6" viewBox="0 0 18 6" aria-hidden="true" focusable="false">
                    <path d="M0 3h16M13 1l3 2-3 2" fill="none" stroke="currentColor" strokeWidth="1" />
                  </svg>
                  <span className="exp-lab__logTo">{l.to}</span>
                </li>
              ))}
            </ul>
          )}
        </div>

        <div className="exp-lab__tools" data-compact={compact || undefined}>
          <div className="exp-lab__toolTabs" role="tablist" aria-label="Restoration tools">
            {TOOLS.map((t) => (
              <button
                key={t.id}
                type="button"
                role="tab"
                id={`exp-lab-tab-${t.id}`}
                aria-selected={tool === t.id}
                aria-controls={`exp-lab-panel-${t.id}`}
                tabIndex={tool === t.id ? 0 : -1}
                title={t.hint}
                className="exp-lab__toolTab"
                onClick={() => setTool(t.id)}
              >
                {t.label}
              </button>
            ))}
          </div>

          <div
            className="exp-lab__toolPanel"
            role="tabpanel"
            id={`exp-lab-panel-${tool}`}
            aria-labelledby={`exp-lab-tab-${tool}`}
          >
            {tool === 'ground' && (
              <>
                <p className="exp-caption">{fabric.note}</p>
                <div className="exp-lab__swatches">
                  {FABRICS.map((f) => (
                    <button
                      key={f.id}
                      type="button"
                      className="exp-lab__swatch"
                      aria-pressed={f.id === state.fabricId}
                      onClick={() => patch({ fabricId: f.id })}
                    >
                      <span
                        className="exp-lab__swatchChip"
                        style={{ background: f.hex }}
                        aria-hidden="true"
                      />
                      <span className="exp-lab__swatchName">{f.name}</span>
                      <span className="exp-meta">{f.gsm}gsm</span>
                    </button>
                  ))}
                </div>
              </>
            )}

            {tool === 'thread' && (
              <>
                <label className="exp-label" htmlFor="exp-lab-block">
                  Block under restoration
                </label>
                <select
                  id="exp-lab-block"
                  className="exp-lab__select"
                  value={block.id}
                  onChange={(e) => setBlockId(e.target.value)}
                >
                  {artifact.design.blocks.map((b) => (
                    <option key={b.id} value={b.id}>
                      {b.label} · {b.type}
                    </option>
                  ))}
                </select>
                <p className="exp-caption" data-definition={def}>
                  {blockThread.code} {blockThread.name} on {fabric.name} — {DEFINITION_COPY[def]}
                </p>
                <div className="exp-lab__threads" role="group" aria-label="Thread box">
                  {THREADS.map((t) => (
                    <button
                      key={t.code}
                      type="button"
                      className="exp-lab__thread"
                      aria-pressed={t.code === blockThread.code}
                      aria-label={`${t.name}, code ${t.code}`}
                      title={`${t.code} ${t.name}`}
                      onClick={() => patch({ threads: { ...state.threads, [block.id]: t.code } })}
                      style={
                        {
                          background: t.hex,
                          '--ink': relativeLuminance(t.hex) > 0.4 ? '#1b1a18' : '#f8f5ef',
                        } as CSSProperties
                      }
                    >
                      <span aria-hidden="true">{t.code}</span>
                    </button>
                  ))}
                </div>
              </>
            )}

            {tool === 'placement' && (
              <>
                <div className="exp-lab__carriers">
                  {GARMENTS.map((g) => (
                    <button
                      key={g.id}
                      type="button"
                      className="exp-action exp-action--quiet"
                      aria-pressed={g.id === state.garmentId}
                      onClick={() =>
                        patch({
                          garmentId: g.id,
                          zoneId: g.zones[0].id,
                          widthMm: Math.min(state.widthMm, g.zones[0].maxWidthMm),
                        })
                      }
                    >
                      {g.name}
                    </button>
                  ))}
                </div>
                <div className="exp-lab__zones" role="group" aria-label="Placement zones">
                  {garment.zones.map((z) => (
                    <button
                      key={z.id}
                      type="button"
                      className="exp-lab__zone"
                      aria-pressed={z.id === state.zoneId}
                      onClick={() =>
                        patch({ zoneId: z.id, widthMm: Math.min(state.widthMm, z.maxWidthMm) })
                      }
                    >
                      {z.label}
                      <span className="exp-meta">max {z.maxWidthMm}mm</span>
                    </button>
                  ))}
                </div>
              </>
            )}

            {tool === 'scale' && (
              <>
                <label className="exp-label" htmlFor="exp-lab-scale">
                  Finished width — {Math.round(state.widthMm)}mm of {zone.maxWidthMm}mm allowed here
                </label>
                <input
                  id="exp-lab-scale"
                  className="exp-lab__range"
                  type="range"
                  min={20}
                  max={zone.maxWidthMm}
                  step={2}
                  value={Math.round(Math.min(state.widthMm, zone.maxWidthMm))}
                  onChange={(e) => patch({ widthMm: Number(e.target.value) })}
                />
                <p className="exp-caption">
                  Drawn against {garment.name} at true scale: {Math.round(state.widthMm)}mm on a{' '}
                  {garment.widthMm}mm carrier.
                </p>
              </>
            )}
          </div>

          {onCommit && (
            <button
              type="button"
              className="exp-action exp-action--primary exp-lab__commit"
              onClick={() => onCommit(state)}
            >
              {commitLabel}
            </button>
          )}
        </div>
      </div>
    </section>
  );
}

/* ------------------------------------------------------------------ bench */

/**
 * The specimen on the bench. Drawn rather than composed from `ArtifactPlate`
 * because placement is the whole point here: the motif has to sit at a real
 * zone, at a real proportion of a real carrier width, or the preview is a lie.
 */
function Bench({
  artifact,
  fabricId,
  garmentId,
  zoneId,
  widthMm,
  threads,
  muted = false,
  highlightZone = false,
}: {
  artifact: ResolvedArtifact;
  fabricId: string;
  garmentId: string;
  zoneId: string;
  widthMm: number;
  threads: Record<string, string>;
  muted?: boolean;
  highlightZone?: boolean;
}) {
  const fabric = fabricById(fabricId);
  const garment = GARMENTS.find((g) => g.id === garmentId) ?? artifact.garment;
  const zone = garment.zones.find((z) => z.id === zoneId) ?? garment.zones[0];
  const [, , gw, gh] = garment.viewBox.split(/\s+/).map(Number);

  // True scale: the design's finished width as a share of the carrier's width.
  const widthPct = (widthMm / garment.widthMm) * 100;
  const aspect = artifact.design.heightMm / artifact.design.widthMm;

  return (
    <div className="exp-lab__stage" style={{ background: fabric.hex }} data-muted={muted || undefined}>
      <div className="exp-lab__carrier">
        <svg viewBox={garment.viewBox} aria-hidden="true" focusable="false">
          <path d={garment.path} fill="rgba(0,0,0,.06)" stroke="rgba(0,0,0,.32)" strokeWidth="1.2" />
          {garment.detail && (
            <path d={garment.detail} fill="none" stroke="rgba(0,0,0,.22)" strokeWidth="0.8" />
          )}
          {highlightZone &&
            garment.zones.map((z) => (
              <circle
                key={z.id}
                cx={z.x}
                cy={z.y}
                r="6"
                className="exp-lab__zoneMark"
                data-on={z.id === zone.id || undefined}
              />
            ))}
        </svg>
        <div
          className="exp-lab__motif"
          style={{
            left: `${(zone.x / gw) * 100}%`,
            top: `${(zone.y / gh) * 100}%`,
            width: `${widthPct}%`,
            aspectRatio: `1 / ${aspect}`,
          }}
        >
          <DesignArt design={artifact.design} threads={threads} aria-hidden="true" focusable="false" />
        </div>
      </div>
    </div>
  );
}
